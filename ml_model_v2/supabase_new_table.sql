-- Creates tables for forecasts and anomalies matching app.py schema.
-- Does not alter existing tables or records without IF NOT EXISTS.

CREATE TABLE IF NOT EXISTS public.weather_forecasts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station TEXT NOT NULL,
  station_id TEXT NOT NULL,
  forecast_date DATE NOT NULL,
  generated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  model_name TEXT NOT NULL DEFAULT 'LightGBM',
  model_version TEXT NOT NULL DEFAULT 'lightgbm-v1',
  max_temp_c DOUBLE PRECISION,
  min_temp_c DOUBLE PRECISION,
  mean_temp_c DOUBLE PRECISION,
  precip_mm DOUBLE PRECISION,
  history_start DATE,
  history_end DATE,
  forecast_horizon_day SMALLINT CHECK (forecast_horizon_day BETWEEN 1 AND 7),
  CONSTRAINT weather_forecasts_station_forecast_date_key UNIQUE (station, forecast_date)
);

CREATE INDEX IF NOT EXISTS weather_forecasts_date_idx ON public.weather_forecasts (forecast_date);
CREATE INDEX IF NOT EXISTS weather_forecasts_station_date_idx ON public.weather_forecasts (station, forecast_date);
ALTER TABLE public.weather_forecasts ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS public.weather_anomalies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  station TEXT NOT NULL,
  station_id TEXT NOT NULL,
  forecast_date DATE NOT NULL,
  variable TEXT NOT NULL,
  forecast_value DOUBLE PRECISION NOT NULL,
  baseline_mean DOUBLE PRECISION NOT NULL,
  baseline_std DOUBLE PRECISION NOT NULL,
  z_score DOUBLE PRECISION NOT NULL,
  threshold DOUBLE PRECISION NOT NULL,
  status TEXT NOT NULL,
  label TEXT NOT NULL,
  severity TEXT NOT NULL,
  detected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT weather_anomalies_unique_key UNIQUE (station, forecast_date, variable)
);

CREATE INDEX IF NOT EXISTS weather_anomalies_date_idx ON public.weather_anomalies (forecast_date);
CREATE INDEX IF NOT EXISTS weather_anomalies_station_date_idx ON public.weather_anomalies (station, forecast_date);
ALTER TABLE public.weather_anomalies ENABLE ROW LEVEL SECURITY;
